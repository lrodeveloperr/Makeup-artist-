// Writes src/face/dim-impact.js: the largest vertex displacement (decimetres) each shape dimension causes at
// +1 and -1. The generator uses it to give every dimension a spread proportional to its visible effect.
// Usage: node tools/makehuman/impact.mjs   (re-run after rebuilding assets/head.bin.gz; tests check it is current)
import fs from 'node:fs';
import { morph } from '../../src/face/head-data.js';
import { readHead } from '../read-head.mjs';

export function measureImpact(head) {
  const V = head.headVertexCount, P0 = morph(head, {});
  const out = {};
  for (const id of head.dims.keys()) {
    out[id] = [1, -1].map((v) => {
      const P = morph(head, { [id]: v });
      let mx = 0;
      for (let k = 0; k < V; k++) mx = Math.max(mx, Math.hypot(P[k * 3] - P0[k * 3], P[k * 3 + 1] - P0[k * 3 + 1], P[k * 3 + 2] - P0[k * 3 + 2]));
      return Math.round(mx * 1000) / 1000;
    });
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const impact = measureImpact(readHead());
  const body = Object.entries(impact).map(([id, [p, m]]) => `  '${id}': [${p}, ${m}],`).join('\n');
  fs.writeFileSync(new URL('../../src/face/dim-impact.js', import.meta.url),
    `// Generated by tools/makehuman/impact.mjs from assets/head.bin.gz. Do not edit.\n// Largest vertex displacement (decimetres) of each shape dimension at +1 and -1.\nexport const DIM_IMPACT = {\n${body}\n};\n`);
  console.log(`src/face/dim-impact.js: ${Object.keys(impact).length} dimensions`);
}
