// Shape dimensions baked into the head asset. Each dimension is a signed value in [-1, 1]: positive
// values blend the "plus" targets, negative values the "minus" targets (MakeHuman's incr/decr pairs).
// Left/right targets are summed into one symmetric dimension. MakeHuman's three ethnicity targets are
// only used to build the neutral reference head (an equal blend), never as a dimension.
const sym = (dir, name) => [`${dir}/l-${name}`, `${dir}/r-${name}`];
const pair = (id, plus, minus) => ({ id, plus: [].concat(plus || []), minus: [].concat(minus || []) });
const bi = (id, dir, name, up = 'incr', down = 'decr') => pair(id, `${dir}/${name}-${up}`, `${dir}/${name}-${down}`);
const biSym = (id, dir, name, up = 'incr', down = 'decr') => pair(id, sym(dir, `${name}-${up}`), sym(dir, `${name}-${down}`));
const one = (id, target) => pair(id, target, null);

